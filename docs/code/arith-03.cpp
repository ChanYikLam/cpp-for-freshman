#include <iostream>

int main()
{
    int a = 7;
    int b = 3;

    std::cout << "7 / 3 = " << a / b << std::endl;
    std::cout << "7 % 3 = " << a % b << std::endl;
    std::cout << "1 + 2 * 3 = " << 1 + 2 * 3 << std::endl;
    std::cout << "(1 + 2) * 3 = " << (1 + 2) * 3 << std::endl;
    std::cout << "1 + 2.0 = " << 1 + 2.0 << std::endl;

    return 0;
}
