#include <iostream>

using namespace std;
int main()
{
    int a = 7;
    int b = 3;

    cout << "7 / 3 = " << a / b << endl;
    cout << "7 % 3 = " << a % b << endl;
    cout << "1 + 2 * 3 = " << 1 + 2 * 3 << endl;
    cout << "(1 + 2) * 3 = " << (1 + 2) * 3 << endl;
    cout << "1 + 2.0 = " << 1 + 2.0 << endl;

    return 0;
}
